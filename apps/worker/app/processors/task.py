"""
タスクプロセッサー

シンプルなタスク処理を行います。
Step 1（Part 2: 実装編）で使用するプロセッサーで、
Queue Storage の基本動作を確認するためのものです。

このプロセッサーは以下の特徴を持ちます:
- ファイル操作を伴わない純粋なタスク処理
- 処理時間をシミュレーション（2秒待機）
- ログ出力による動作確認

実際のプロダクション環境では、ここでバッチ処理や
計算処理などの具体的なビジネスロジックを実装します。
"""

# ============================================================
# インポート
# ============================================================

# 標準ライブラリ: 非同期I/O処理用モジュール
# asyncio.sleep: 処理時間のシミュレーションに使用
import asyncio
# 標準ライブラリ: ログ出力用モジュール
import logging
# 標準ライブラリ: 型ヒント用モジュール
from typing import Any

# アプリケーション内部: プロセッサー基底クラス
# すべてのプロセッサーはこのクラスを継承する
from apps.worker.app.processors.base import BaseProcessor

# ============================================================
# ロガー設定
# ============================================================

# このモジュール用のロガーを取得
# __name__ を使用することで、モジュール階層に沿ったログ出力が可能
logger = logging.getLogger(__name__)


# ============================================================
# タスクプロセッサークラス
# ============================================================


class TaskProcessor(BaseProcessor):
    """
    タスクプロセッサー

    メッセージを受け取り、シンプルな処理を行います。

    使用シナリオ:
    - POST /tasks エンドポイントから投入されたタスクの処理
    - Queue Storage の基本動作確認
    - Worker のメッセージ処理フローのテスト

    処理フロー:
    1. メッセージからタスク情報を抽出
    2. ログ出力（処理開始）
    3. 処理時間をシミュレーション
    4. ログ出力（処理完了）
    5. 処理結果を返却
    """

    @property
    def processor_type(self) -> str:
        """
        プロセッサータイプを返す

        Returns:
            str: "task" - このプロセッサーの識別子
                 メッセージの processor_type が "task" の場合に選択される
        """
        return "task"

    async def execute(self, data: dict[str, Any]) -> dict[str, Any]:
        """
        タスクを処理

        メッセージからタスク情報を取得し、処理を実行します。
        実際の処理はシミュレーション（2秒待機）で代替しています。

        Args:
            data: メッセージデータ（キューから取得した JSON データ）
                - task_id: タスクID（API が生成した一意識別子）
                - name: タスク名（ユーザーが指定した名前）
                - description: 説明（オプション）

        Returns:
            dict: 処理結果
                - status: "completed"（処理成功）
                - task_id: 処理したタスクのID
                - message: 処理完了メッセージ

        Note:
            エラーが発生した場合は例外をスローし、
            Worker がリトライや DLQ 移動を行います。
        """
        # ============================================================
        # メッセージからタスク情報を抽出
        # ============================================================
        # get() を使用してキーが存在しない場合のデフォルト値を設定
        task_id = data.get("task_id", "unknown")
        name = data.get("name", "unknown")
        # description は現在使用していないが、将来の拡張用に取得
        description = data.get("description", "")

        # ============================================================
        # 処理開始ログ
        # ============================================================
        # タスクID と名前を含めてログ出力（デバッグ・監視用）
        logger.info(f"タスク処理開始: {task_id} - {name}")

        # ============================================================
        # 処理時間のシミュレーション
        # ============================================================
        # 実際のアプリケーションでは、ここで具体的な処理を行う
        # 例: 外部 API 呼び出し、データ変換、計算処理など
        # 2秒の待機で処理に時間がかかることをシミュレート
        await asyncio.sleep(2)

        # ============================================================
        # 処理完了ログ
        # ============================================================
        logger.info(f"タスク処理完了: {task_id}")

        # ============================================================
        # 処理結果を返却
        # ============================================================
        # Worker はこの結果を受け取り、メッセージを削除する
        return {
            # 処理ステータス: Worker が成功/失敗を判断
            "status": "completed",
            # タスクID: どのタスクが処理されたかを特定
            "task_id": task_id,
            # 完了メッセージ: ログや通知に使用可能
            "message": f"タスク '{name}' の処理が完了しました",
        }
