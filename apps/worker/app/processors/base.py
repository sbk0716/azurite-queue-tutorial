"""
プロセッサー基底クラス

すべてのプロセッサーはこのクラスを継承します。
Strategy パターンを採用し、メッセージの種類に応じて
適切なプロセッサーを選択・実行できるようにしています。
"""

# ============================================================
# インポート
# ============================================================

# 標準ライブラリ: 抽象基底クラス定義用モジュール
# ABC: 抽象基底クラスを定義するための親クラス
# abstractmethod: 抽象メソッドを定義するデコレータ
from abc import ABC, abstractmethod
# 標準ライブラリ: 型ヒント用モジュール
# Any: 任意の型を許容する型ヒント
from typing import Any


# ============================================================
# プロセッサー基底クラス
# ============================================================


class BaseProcessor(ABC):
    """
    プロセッサー基底クラス

    メッセージ処理の共通インターフェースを定義します。
    新しいプロセッサーを追加する際は、このクラスを継承し、
    execute メソッドと processor_type プロパティを実装してください。

    設計上の決定:
    - 抽象基底クラス（ABC）を使用して、インターフェースを強制
    - 非同期処理（async/await）を前提とした設計
    - Strategy パターンにより、メッセージタイプごとに処理を分離
    """

    @abstractmethod
    async def execute(self, data: dict[str, Any]) -> dict[str, Any]:
        """
        メッセージを処理

        このメソッドは各プロセッサーで必ず実装する必要があります。
        メッセージの内容に応じた具体的な処理を行い、
        処理結果を辞書形式で返却します。

        Args:
            data: メッセージデータ（JSON からパースされた辞書）
                  キューから取得したメッセージの内容がそのまま渡されます

        Returns:
            dict: 処理結果
                  - status: 処理ステータス（"completed" / "failed" など）
                  - その他、プロセッサー固有の結果データ

        Raises:
            Exception: 処理中にエラーが発生した場合
                       Worker がキャッチしてリトライや DLQ 移動を行います
        """
        pass

    @property
    @abstractmethod
    def processor_type(self) -> str:
        """
        プロセッサータイプを返す

        Worker がメッセージの processor_type フィールドと照合し、
        適切なプロセッサーを選択するために使用します。

        Returns:
            str: プロセッサーの識別子（例: "task", "file"）
        """
        pass
